package com.linksnip.urlshortener.service;

import com.linksnip.urlshortener.dto.request.CreateShortUrlRequest;
import com.linksnip.urlshortener.dto.response.ShortUrlResponse;
import com.linksnip.urlshortener.dto.response.UrlDetailsResponse;
import com.linksnip.urlshortener.entity.Url;
import com.linksnip.urlshortener.exception.AliasAlreadyExistsException;
import com.linksnip.urlshortener.exception.ReservedAliasException;
import com.linksnip.urlshortener.exception.UrlExpiredException;
import com.linksnip.urlshortener.exception.UrlNotFoundException;
import com.linksnip.urlshortener.repository.UrlRepository;
import com.linksnip.urlshortener.util.ReservedShortCodes;
import java.time.Instant;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

@Service
public class UrlService {

    private static final int MAX_AUTO_CODE_ATTEMPTS = 5;

    private final UrlRepository urlRepository;
    private final ShortCodeGeneratorService shortCodeGeneratorService;
    private final UrlCacheService urlCacheService;
    private final ClickTrackingService clickTrackingService;
    private final String baseUrl;

    public UrlService(
        UrlRepository urlRepository,
        ShortCodeGeneratorService shortCodeGeneratorService,
        UrlCacheService urlCacheService,
        ClickTrackingService clickTrackingService,
        @Value("${app.base-url}") String baseUrl
    ) {
        this.urlRepository = urlRepository;
        this.shortCodeGeneratorService = shortCodeGeneratorService;
        this.urlCacheService = urlCacheService;
        this.clickTrackingService = clickTrackingService;
        this.baseUrl = baseUrl;
    }

    @Transactional
    public ShortUrlResponse createShortUrl(CreateShortUrlRequest request, Long ownerId) {
        Url url = request.customAlias() != null
            ? buildCustomAliasUrl(request, ownerId)
            : buildAutoGeneratedUrl(request, ownerId);

        urlRepository.save(url);

        return toResponse(url);
    }

    @Transactional(readOnly = true)
    public String resolveLongUrl(String shortCode, String referrer, String userAgent, String ipAddress) {
        UrlCacheEntry entry = urlCacheService.get(shortCode)
            .orElseGet(() -> loadAndCache(shortCode));

        if (!entry.isActive()) {
            throw new UrlNotFoundException("Short URL not found: " + shortCode);
        }
        if (entry.getExpiresAt() != null && entry.getExpiresAt().isBefore(Instant.now())) {
            throw new UrlExpiredException("Short URL has expired: " + shortCode);
        }

        clickTrackingService.recordClickAsync(entry.getId(), referrer, userAgent, ipAddress);

        return entry.getLongUrl();
    }

    @Transactional(readOnly = true)
    public UrlDetailsResponse getDetails(String shortCode, Long requestingUserId) {
        Url url = urlRepository.findByShortCode(shortCode)
            .filter(Url::isActive)
            .orElseThrow(() -> new UrlNotFoundException("Short URL not found: " + shortCode));

        if (url.getUserId() != null && !url.getUserId().equals(requestingUserId)) {
            throw new AccessDeniedException("You do not have access to this short URL");
        }

        return toDetailsResponse(url);
    }

    @Transactional(readOnly = true)
    public Page<UrlDetailsResponse> listUrls(Long userId, Pageable pageable) {
        return urlRepository.findByUserIdAndActiveTrue(userId, pageable).map(this::toDetailsResponse);
    }

    @Transactional
    public void deleteShortUrl(String shortCode, Long requestingUserId) {
        Url url = urlRepository.findByShortCode(shortCode)
            .filter(Url::isActive)
            .orElseThrow(() -> new UrlNotFoundException("Short URL not found: " + shortCode));

        if (url.getUserId() == null || !url.getUserId().equals(requestingUserId)) {
            throw new AccessDeniedException("You do not own this short URL");
        }

        url.setActive(false);
        url.setDeletedAt(Instant.now());
        urlRepository.save(url);

        urlCacheService.evict(shortCode);
    }

    private UrlCacheEntry loadAndCache(String shortCode) {
        Url url = urlRepository.findByShortCode(shortCode)
            .orElseThrow(() -> new UrlNotFoundException("Short URL not found: " + shortCode));

        UrlCacheEntry entry = UrlCacheEntry.builder()
            .id(url.getId())
            .longUrl(url.getLongUrl())
            .expiresAt(url.getExpiresAt())
            .active(url.isActive())
            .build();

        urlCacheService.put(shortCode, entry);
        return entry;
    }

    private Url buildCustomAliasUrl(CreateShortUrlRequest request, Long ownerId) {
        String alias = request.customAlias();

        if (ReservedShortCodes.isReserved(alias)) {
            throw new ReservedAliasException("'" + alias + "' is a reserved word and cannot be used as an alias");
        }
        if (urlRepository.existsByShortCode(alias)) {
            throw new AliasAlreadyExistsException("Alias already in use: " + alias);
        }

        ShortCodeGeneratorService.GeneratedId generated = shortCodeGeneratorService.nextIdForCustomAlias();

        return Url.builder()
            .id(generated.id())
            .shortCode(alias)
            .longUrl(request.longUrl())
            .userId(ownerId)
            .customAlias(true)
            .clickCount(0L)
            .active(true)
            .createdAt(Instant.now())
            .expiresAt(request.expiresAt())
            .build();
    }

    private Url buildAutoGeneratedUrl(CreateShortUrlRequest request, Long ownerId) {
        ShortCodeGeneratorService.GeneratedId generated = shortCodeGeneratorService.nextAutoGeneratedCode();

        int attempts = 1;
        while (urlRepository.existsByShortCode(generated.shortCode())) {
            if (attempts++ >= MAX_AUTO_CODE_ATTEMPTS) {
                throw new IllegalStateException("Unable to generate a unique short code after " + attempts + " attempts");
            }
            generated = shortCodeGeneratorService.nextAutoGeneratedCode();
        }

        return Url.builder()
            .id(generated.id())
            .shortCode(generated.shortCode())
            .longUrl(request.longUrl())
            .userId(ownerId)
            .customAlias(false)
            .clickCount(0L)
            .active(true)
            .createdAt(Instant.now())
            .expiresAt(request.expiresAt())
            .build();
    }

    private ShortUrlResponse toResponse(Url url) {
        return new ShortUrlResponse(
            url.getShortCode(),
            baseUrl + "/" + url.getShortCode(),
            url.getLongUrl(),
            url.getCreatedAt(),
            url.getExpiresAt()
        );
    }

    private UrlDetailsResponse toDetailsResponse(Url url) {
        return new UrlDetailsResponse(
            url.getShortCode(),
            baseUrl + "/" + url.getShortCode(),
            url.getLongUrl(),
            url.getCreatedAt(),
            url.getExpiresAt(),
            url.getClickCount(),
            url.isActive()
        );
    }
}
