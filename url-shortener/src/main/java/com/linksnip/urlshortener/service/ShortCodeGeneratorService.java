package com.linksnip.urlshortener.service;

import com.linksnip.urlshortener.repository.UrlRepository;
import com.linksnip.urlshortener.util.Base62Encoder;
import org.springframework.stereotype.Service;

@Service
public class ShortCodeGeneratorService {

    private final UrlRepository urlRepository;

    public ShortCodeGeneratorService(UrlRepository urlRepository) {
        this.urlRepository = urlRepository;
    }

    public record GeneratedId(Long id, String shortCode) {
    }

    public GeneratedId nextAutoGeneratedCode() {
        Long id = urlRepository.nextId();
        return new GeneratedId(id, Base62Encoder.encode(id));
    }

    public GeneratedId nextIdForCustomAlias() {
        Long id = urlRepository.nextId();
        return new GeneratedId(id, null);
    }
}
